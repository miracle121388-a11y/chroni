import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const command = process.platform === "win32" ? (process.env.ComSpec ?? "cmd.exe") : "pnpm";
const args = process.platform === "win32" ? ["/d", "/s", "/c", "pnpm licenses list --json --prod"] : ["licenses", "list", "--json", "--prod"];
const raw = execFileSync(command, args, {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 32 * 1024 * 1024,
});
const licenses = JSON.parse(raw);
const rows = Object.entries(licenses).flatMap(([license, packages]) => packages.map((entry) => ({
  name: entry.name,
  versions: [...entry.versions].sort().join(", "),
  license,
  homepage: entry.homepage ?? "",
})));
rows.sort((left, right) => left.name.localeCompare(right.name) || left.versions.localeCompare(right.versions));
const markdown = `# Production dependency license inventory

Generated by \`pnpm run notices:generate\` from installed production dependencies. Filesystem paths and author metadata are intentionally omitted. Regenerate after dependency changes; \`pnpm-lock.yaml\` remains the exact version authority.

| Package | Version(s) | License | Homepage |
| --- | --- | --- | --- |
${rows.map((row) => `| ${escapeCell(row.name)} | ${escapeCell(row.versions)} | ${escapeCell(row.license)} | ${row.homepage ? `[link](${row.homepage})` : ""} |`).join("\n")}
`;
const output = resolve(root, "THIRD_PARTY_DEPENDENCIES.md");
writeFileSync(output, markdown, "utf8");
console.log(`Wrote ${rows.length} production dependency entries to ${output}`);

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}
